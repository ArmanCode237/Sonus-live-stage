"""Synthesis engine(s) of every synth factory preset, for the sound browser's MOTOR filter.

Reads presets/synth/factory/NNN.json and writes webui/src/data/synthFactoryEngines.ts
({ id: [synthesisType, ...] } of the enabled layers). Run after changing the factory bank:
    python tools/build_factory_engines.py
"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
engines = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'presets', 'synth', 'factory', '*.json'))):
    pid = int(re.sub(r'\D', '', os.path.basename(path)))
    with open(path, encoding='utf8') as f:
        doc = json.load(f)
    params = doc.get('params', doc)
    types = sorted({int(l.get('synthesisType', 0)) for l in params.get('layers', []) if l.get('enabled')})
    engines[pid] = types or [0]
out = os.path.join(ROOT, 'webui', 'src', 'data', 'synthFactoryEngines.ts')
with open(out, 'w', encoding='utf8', newline='\n') as f:
    f.write('// Generated by tools/build_factory_engines.py from presets/synth/factory (do not edit).\n')
    f.write('// Synthesis types (SYNTH_SYNTHESIS_TYPES index) of the enabled layers of each factory preset.\n')
    f.write('export const SYNTH_FACTORY_ENGINES: Readonly<Record<number, readonly number[]>> = ')
    f.write(json.dumps(engines, separators=(',', ':')) + ';\n')
print(f'{len(engines)} presets -> {out}')
